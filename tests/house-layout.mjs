import assert from 'node:assert/strict';
import {familyRoomObjects,upgradeHouseReview,removeDryBar,furnitureBounds,HOUSE_REVIEW_REVISION} from '../dist/house-layout.js';
import {importDesignStates,createDesignStates} from '../dist/suite-state.js';
const find=id=>familyRoomObjects.find(o=>o.id===id),sofa=find('sofa'),tv=find('family-tv'),dining=find('dining'),coffee=find('coffee');
const facing=o=>({x:-Math.sin(o.rotation*Math.PI/180),z:-Math.cos(o.rotation*Math.PI/180)});
assert.ok(facing(sofa).x>.99,'Seated viewers must face north (+X)');
assert.ok(facing(tv).x<-.99,'The TV must face south toward the sofa');
assert.ok(tv.x>sofa.x&&Math.abs(tv.z-sofa.z)<.01,'TV and sofa centerlines align');
assert.ok(dining.x<40&&dining.z<10,'Dining belongs in the southwest corner');
const sb=furnitureBounds(sofa),cb=furnitureBounds(coffee);
assert.ok(cb[0]-sb[2]>=16/12,'At least 16 inches between sofa and coffee table');
assert.ok(sb[0]-40>=4,'Keep a four-foot route behind the sofa beside the island');
const main={schema:1,objects:[{id:'sofa',x:48,z:17},{id:'custom',name:'User furniture'}],lights:[],kitchen:{custom:'preserve'}};
const updated=upgradeHouseReview(main,'main');assert.equal(updated.kitchen.custom,'preserve');assert.ok(updated.objects.some(o=>o.id==='custom'));
assert.equal(main.objects[0].x,48,'Migration does not mutate the input');
updated.objects.find(o=>o.id==='sofa').x=46.8;
assert.deepEqual(upgradeHouseReview(updated,'main'),updated,'Future furniture edits survive subsequent reloads');
const basement={schema:1,objects:[{id:'b-drybar',name:'Dry bar'},{id:'keep',name:'Other cabinet'}],lights:[]};
const levels=createDesignStates(main,basement);for(const floor of Object.values(levels))assert.ok(!floor.basement.objects.some(o=>o.id==='b-drybar'));
const old=structuredClone(levels);delete old.revised.main.houseReviewRevision;
for(const floor of Object.values(old))floor.basement.objects.push({id:'b-drybar',name:'Dry bar'});
const result=importDesignStates({schema:4,design:'revised',designs:old},s=>s?.schema===1&&Array.isArray(s.objects),basement);
assert.equal(result.designs.revised.main.houseReviewRevision,HOUSE_REVIEW_REVISION);
for(const floor of Object.values(result.designs))assert.ok(!floor.basement.objects.some(o=>/dry bar/i.test(o.name)));
console.log('North-facing seating, southwest dining, clearances, saved-layout migration and dry-bar removal passed.');
